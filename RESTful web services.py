""" REST  - Representational State Transfer.
In REST architectural style all data and functionalities which resides in server
are treated as RESOURCES. So for a client everything inside the server is a resource.
Each resource is mapped with a unique link called URI(Uniform Resource Identifier.)
So to access the resource we must know its URI.
The content of a resource is represented in any format: XML , Image, HTML, text , Pdf , JSON.

So in RESTful services we can decide what should be the Representation of our data/ resources.
eg. DATA CONTENT : REPRESENTATION (XML,JSON,Pdf,Text)

STATE - The term state means CONDITION. 
When a client interacts with a resource it perfoms a series of events. 
STATEful PROCESS - when the server records all of its users state.
STATELESS PROCESS - when the server is unable to track the users interaction with the
resource.
The REST architectural style is designed to use the STATELESS communication Protocol.(the HTTP).
STATEful : session, login, basket, dynamic content.
STATEless : no session , no login , no basket , static content.

TRANSFER - The exchange of resource presentations using different protocols.
 """
